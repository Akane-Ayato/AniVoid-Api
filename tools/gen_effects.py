"""Generate assets/effects.css (the ~100 cosmetic effects) from app/effects.py.
Usage:  python tools/gen_effects.py ../AniVoidTV/assets/effects.css
Every item id "frame.spin_aurora" becomes the class .fx-frame-spin_aurora."""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from app import effects as E  # noqa: E402

PAL, OUT = E.PALETTES, []


def cls(iid):
    return "fx-" + iid.replace(".", "-")


def A(color, alpha):          # alpha as 2 hex digits, only valid for #rrggbb colours
    return color + alpha if color.startswith("#") else color


def conic(pal, extra=""):
    if pal == "rainbow":
        return "conic-gradient(red,orange,yellow,lime,cyan,blue,magenta,red)"
    c1, c2, c3 = PAL[pal]
    return f"conic-gradient({c1},{c2},{c3},{c1}{extra})"


def lin(pal, deg=90, loop=True):
    c1, c2, c3 = PAL[pal]
    return f"linear-gradient({deg}deg,{c1},{c2},{c3}{',' + c1 if loop else ''})"


RING_MASK = "-webkit-mask:radial-gradient(farthest-side,transparent calc(100% - var(--rw,3px)),#000 calc(100% - var(--rw,3px) + .5px));mask:radial-gradient(farthest-side,transparent calc(100% - var(--rw,3px)),#000 calc(100% - var(--rw,3px) + .5px));"

OUT.append("""/* GENERATED by tools/gen_effects.py. Do not edit by hand. */
/* ---- avatar frames ---- */
.av-ring,.av-ring2{position:absolute;border-radius:50%;pointer-events:none;display:none}
.av{--r:calc(var(--s) * .5 + 7px)}
@keyframes avSpin{to{transform:rotate(360deg)}}
@keyframes avSpinR{to{transform:rotate(-360deg)}}
@keyframes avPulse{0%,100%{box-shadow:0 0 0 2px var(--c),0 0 6px 1px var(--c)}50%{box-shadow:0 0 0 3px var(--c),0 0 18px 5px var(--c)}}
@keyframes avBlob{0%{border-radius:58% 42% 55% 45%/48% 58% 42% 52%;transform:rotate(0)}33%{border-radius:42% 58% 45% 55%/58% 44% 56% 42%;transform:rotate(120deg)}66%{border-radius:54% 46% 62% 38%/42% 56% 44% 58%;transform:rotate(240deg)}100%{border-radius:58% 42% 55% 45%/48% 58% 42% 52%;transform:rotate(360deg)}}
@keyframes avOrbit{from{transform:rotate(0) translateX(var(--r))}to{transform:rotate(360deg) translateX(var(--r))}}
@keyframes avRipple{0%{transform:scale(1);opacity:.85}100%{transform:scale(1.55);opacity:0}}
""")

# ---------- frames
for iid, (fam, p) in E.RECIPES.items():
    if not iid.startswith("frame."):
        continue
    k = f".{cls(iid)}"
    if fam == "spin":
        OUT.append(f"{k} .av-ring{{display:block;inset:-4px;background:{conic(p['pal'])};{RING_MASK}animation:avSpin 5s linear infinite}}")
    elif fam == "pulse":
        c = E.GLOWS[p["c"]]
        OUT.append(f"{k}{{--c:{c}}}{k} .av-ring{{display:block;inset:-3px}}{k} .av-ring{{animation:avPulse 2.2s ease-in-out infinite}}")
    elif fam == "dash":
        c = E.GLOWS[p["c"]]
        OUT.append(f"{k} .av-ring{{display:block;inset:-5px;border:2.5px dashed {c};animation:avSpin 9s linear infinite;filter:drop-shadow(0 0 4px {A(c, '99')})}}")
    elif fam == "twin":
        OUT.append(f"{k} .av-ring{{display:block;inset:-4px;background:{conic(p['pal'])};{RING_MASK}animation:avSpin 4s linear infinite}}"
                   f"{k} .av-ring2{{display:block;inset:-9px;background:{conic(p['pal'], ',transparent 55%')};--rw:2px;{RING_MASK}animation:avSpinR 7s linear infinite;opacity:.9}}")
    elif fam == "blob":
        OUT.append(f"{k} .av-ring{{display:block;inset:-5px;background:{lin(p['pal'], 135, False)};animation:avBlob 7s ease-in-out infinite;filter:saturate(1.2)}}")
    elif fam == "orbit":
        c = E.GLOWS[p["c"]]
        OUT.append(f"{k} .av-ring{{display:block;inset:-4px;border:1px solid {A(c, '55')}}}"
                   f"{k}::before,{k}::after{{content:'';position:absolute;top:50%;left:50%;width:7px;height:7px;margin:-3.5px;border-radius:50%;background:{c};box-shadow:0 0 8px 2px {c};pointer-events:none;animation:avOrbit 3.2s linear infinite}}"
                   f"{k}::after{{animation-delay:-1.6s;width:5px;height:5px;margin:-2.5px}}")
    elif fam == "ripple":
        c = E.PALETTES[p["pal"]][1] if p["pal"] else E.GLOWS[p["c"]]
        OUT.append(f"{k} .av-ring,{k} .av-ring2{{display:block;inset:0;border:2px solid {c};animation:avRipple 2.6s ease-out infinite}}{k} .av-ring2{{animation-delay:1.3s}}")

# ---------- name effects
OUT.append("""
/* ---- name effects (.nm) ---- */
.nm{font-weight:700;position:relative;display:inline-block;max-width:100%;overflow:hidden;text-overflow:ellipsis;white-space:nowrap;vertical-align:bottom}
.nm[class*="fx-name-grad"],.nm[class*="fx-name-shimmer"],.nm.fx-name-rainbow,.nm.fx-name-metal_gold{-webkit-background-clip:text;background-clip:text;color:transparent;-webkit-text-fill-color:transparent}
@keyframes nmFlow{to{background-position:200% 0}}
@keyframes nmGlow{0%,100%{text-shadow:0 0 4px var(--c),0 0 9px var(--c)}50%{text-shadow:0 0 8px var(--c),0 0 22px var(--c),0 0 34px var(--c)}}
@keyframes nmShimmer{from{background-position:150% 0}to{background-position:-50% 0}}
@keyframes nmFlicker{0%,19%,22%,62%,64%,100%{opacity:1}20%,21%,63%{opacity:.45}}
@keyframes nmGlitchA{0%,90%,100%{transform:translate(0);clip-path:inset(0 0 0 0)}92%{transform:translate(-2px,1px);clip-path:inset(10% 0 55% 0)}95%{transform:translate(2px,-1px);clip-path:inset(60% 0 8% 0)}}
@keyframes nmGlitchB{0%,88%,100%{transform:translate(0);clip-path:inset(0 0 0 0)}90%{transform:translate(2px,0);clip-path:inset(45% 0 20% 0)}94%{transform:translate(-2px,1px);clip-path:inset(5% 0 70% 0)}}
@keyframes nmMetal{to{background-position:0 200%}}
""")
for iid, (fam, p) in E.RECIPES.items():
    if not iid.startswith("name."):
        continue
    k = f".nm.{cls(iid)}"
    if fam == "grad":
        OUT.append(f"{k}{{background-image:{lin(p['pal'], 90)};background-size:200% auto;animation:nmFlow 4s linear infinite}}")
    elif fam == "glow":
        OUT.append(f"{k}{{--c:{p['col']};color:#fff;animation:nmGlow 2.6s ease-in-out infinite}}")
    elif fam == "shimmer":
        c = p["col"]
        OUT.append(f"{k}{{background-image:linear-gradient(110deg,{c} 38%,#fff 50%,{c} 62%);background-size:250% 100%;animation:nmShimmer 2.8s linear infinite}}")
    elif fam == "flicker":
        c = p["col"]
        OUT.append(f"{k}{{color:{c};text-shadow:0 0 3px {c},0 0 10px {c},0 0 22px {c};animation:nmFlicker 3.4s infinite}}")
    elif fam == "glitch":
        c = p["col"]
        OUT.append(f"{k}{{color:#fff;overflow:visible}}{k}::before,{k}::after{{content:attr(data-text);position:absolute;left:0;top:0;width:100%;overflow:hidden}}"
                   f"{k}::before{{color:{c};animation:nmGlitchA 3s infinite}}{k}::after{{color:#ff3df2;animation:nmGlitchB 3.4s infinite}}")
    elif fam == "rainbowtext":
        OUT.append(f"{k}{{background-image:linear-gradient(90deg,red,orange,yellow,lime,cyan,blue,magenta,red);background-size:300% auto;animation:nmFlow 5s linear infinite}}")
    elif fam == "metal":
        OUT.append(f"{k}{{background-image:linear-gradient(180deg,#fff7c2 0%,#f5c542 30%,#b8860b 50%,#ffe58f 70%,#fff7c2 100%);background-size:100% 200%;animation:nmMetal 3s linear infinite;filter:drop-shadow(0 1px 0 #6b4a00)}}")
    elif fam == "outline":
        c = p["col"]
        OUT.append(f"{k}{{color:transparent;-webkit-text-stroke:1px {c};text-shadow:0 0 10px {A(c, '88')}}}")

# ---------- banner overlays
OUT.append("""
/* ---- banner overlays (.bfx sits on top of the banner picture) ---- */
.bfx{position:absolute;inset:0;pointer-events:none;overflow:hidden}
.bfx::before,.bfx::after{content:"";position:absolute;inset:0}
@keyframes bfxDrift{0%{transform:translate3d(-4%,-2%,0) scale(1.05)}100%{transform:translate3d(4%,3%,0) scale(1.18)}}
@keyframes bfxTwinkle{0%,100%{opacity:.35}50%{opacity:1}}
@keyframes bfxRain{to{background-position:-60px 160px}}
@keyframes bfxScan{from{transform:translateY(-100%)}to{transform:translateY(100%)}}
@keyframes bfxGrid{to{background-position:0 28px,28px 0}}
@keyframes bfxFloat{0%{transform:translateY(8%) scale(1)}100%{transform:translateY(-10%) scale(1.12)}}
@keyframes bfxWave{to{background-position:240px 0}}
@keyframes bfxRise{to{background-position:0 -240px,30px -300px}}
""")
for iid, (fam, p) in E.RECIPES.items():
    if not iid.startswith("banner."):
        continue
    k = f".bfx.{cls(iid)}"
    if fam == "b_aurora":
        c1, c2, c3 = PAL[p["pal"]]
        OUT.append(f"{k}::before{{background:radial-gradient(40% 60% at 20% 30%,{A(c1, 'bb')},transparent 70%),radial-gradient(45% 55% at 75% 40%,{A(c2, 'aa')},transparent 70%),radial-gradient(50% 50% at 50% 95%,{A(c3, '99')},transparent 70%);filter:blur(16px);mix-blend-mode:screen;animation:bfxDrift 11s ease-in-out infinite alternate}}")
    elif fam == "b_stars":
        c = p["col"]
        dots = ",".join(f"radial-gradient({r}px {r}px at {x}px {y}px,{c},transparent 60%)" for x, y, r in [(20, 30, 1.6), (90, 70, 1.2), (150, 20, 1.8), (60, 140, 1.2), (180, 120, 1.5), (120, 170, 1.1), (30, 100, 1.0)])
        OUT.append(f"{k}::before{{background-image:{dots};background-size:200px 200px;animation:bfxTwinkle 3.5s ease-in-out infinite}}"
                   f"{k}::after{{background-image:{dots};background-size:260px 230px;background-position:70px 40px;animation:bfxTwinkle 5s ease-in-out infinite reverse;opacity:.7}}")
    elif fam == "b_rain":
        c = p["col"]
        OUT.append(f"{k}::before{{background:linear-gradient(105deg,transparent 48%,{A(c, '88')} 50%,transparent 52%);background-size:26px 90px;animation:bfxRain .9s linear infinite;opacity:.7}}")
    elif fam == "b_scan":
        c = p["col"]
        OUT.append(f"{k}::before{{background:repeating-linear-gradient(0deg,transparent 0 2px,{A(c, '22')} 2px 3px)}}"
                   f"{k}::after{{background:linear-gradient(180deg,transparent,{A(c, '33')} 50%,transparent);height:30%;inset:0 0 auto 0;animation:bfxScan 4s linear infinite}}")
    elif fam == "b_grid":
        c = p["col"]
        OUT.append(f"{k}::before{{background-image:linear-gradient({A(c, '44')} 1px,transparent 1px),linear-gradient(90deg,{A(c, '44')} 1px,transparent 1px);background-size:28px 28px;animation:bfxGrid 4s linear infinite;-webkit-mask:linear-gradient(transparent,#000);mask:linear-gradient(transparent,#000)}}")
    elif fam == "b_bokeh":
        c1, c2, c3 = PAL[p["pal"]]
        circles = ",".join(f"radial-gradient(circle at {x}% {y}%,{A(c, 'aa')} 0 {r}px,transparent {r + 1}px)" for x, y, r, c in [(12, 70, 22, c1), (30, 30, 14, c2), (48, 78, 30, c3), (66, 40, 18, c1), (82, 72, 26, c2), (92, 25, 12, c3)])
        OUT.append(f"{k}::before{{background:{circles};filter:blur(3px);animation:bfxFloat 7s ease-in-out infinite alternate}}")
    elif fam == "b_waves":
        c1, c2, c3 = PAL[p["pal"]]
        OUT.append(f"{k}::before{{background:radial-gradient(ellipse 120px 34px at 60px 100%,{A(c1, '77')} 0 98%,transparent 100%) 0 100%/120px 50% repeat-x;animation:bfxWave 6s linear infinite}}"
                   f"{k}::after{{background:radial-gradient(ellipse 160px 44px at 80px 100%,{A(c2, '66')} 0 98%,transparent 100%) 0 100%/160px 65% repeat-x;animation:bfxWave 9s linear infinite reverse}}")
    elif fam == "b_sparks":
        c = p["col"]
        pts = ",".join(f"radial-gradient(2px 2px at {x}px {y}px,{c},transparent 70%)" for x, y in [(15, 40), (60, 120), (105, 20), (150, 90), (200, 150), (40, 190), (130, 210), (210, 60)])
        OUT.append(f"{k}::before{{background-image:{pts};background-size:230px 240px;animation:bfxRise 5s linear infinite}}"
                   f"{k}::after{{background-image:{pts};background-size:300px 260px;background-position:90px 30px;animation:bfxRise 8s linear infinite;opacity:.6}}")

# ---------- card styles (comment bubbles + profile cards)
OUT.append("""
/* ---- card styles (apply to .cardfx containers) ---- */
@keyframes cardFlow{to{background-position:300% 0}}
@keyframes cardHolo{from{background-position:0 0}to{background-position:300% 0}}
""")
for iid, (fam, p) in E.RECIPES.items():
    if not iid.startswith("card."):
        continue
    k = f".cardfx.{cls(iid)}"
    if fam == "c_gborder":
        c1, c2, c3 = PAL[p["pal"]]
        OUT.append(f"{k}{{border:1px solid transparent;background:linear-gradient(var(--bg-raise),var(--bg-raise)) padding-box,linear-gradient(135deg,{c1},{c2},{c3}) border-box;box-shadow:0 0 28px -12px {A(c2, 'cc')}}}")
    elif fam == "c_glass":
        c = p["col"]
        OUT.append(f"{k}{{background:linear-gradient(135deg,{A(c, '22')},transparent 60%),rgba(255,255,255,.04);border:1px solid {A(c, '55')};-webkit-backdrop-filter:blur(10px);backdrop-filter:blur(10px)}}")
    elif fam == "c_holo":
        c1, c2, c3 = PAL[p["pal"]]
        OUT.append(f"{k}{{background:linear-gradient(115deg,var(--bg-raise) 28%,{A(c1, '33')} 42%,{A(c2, '33')} 52%,{A(c3, '33')} 62%,var(--bg-raise) 76%);background-size:300% 100%;animation:cardHolo 7s linear infinite;border:1px solid {A(c2, '77')}}}")
    elif fam == "c_neon":
        c = p["col"]
        OUT.append(f"{k}{{border:1px solid {c};box-shadow:0 0 0 1px {A(c, '33')},0 0 20px -3px {A(c, '77')},inset 0 0 22px -10px {A(c, '88')}}}")
    elif fam == "c_flow":
        c1, c2, c3 = PAL[p["pal"]]
        OUT.append(f"{k}{{background:linear-gradient(120deg,{A(c1, '2a')},{A(c2, '2a')},{A(c3, '2a')},{A(c1, '2a')}) 0 0/300% 100%,var(--bg-raise);animation:cardFlow 9s linear infinite;border:1px solid {A(c2, '66')}}}")

# ---------- banner presets (free, no upload needed)
PRESETS = ["#4ff0d2,#8a7bff", "#ff5fa8,#8a7bff", "#ffb347,#ff5fa8", "#00e5ff,#2979ff", "#b6ff3b,#00bfa5", "#ff9ae6,#8a3dff", "#1a2342,#4ff0d2", "#0a1020,#ff5fa8"]
OUT.append("\n/* ---- free banner presets ---- */")
for i, pr in enumerate(PRESETS, 1):
    a, b = pr.split(",")
    OUT.append(f".bp-p{i}{{background:radial-gradient(60% 90% at 15% 20%,{A(a, 'cc')},transparent 70%),radial-gradient(60% 90% at 90% 80%,{A(b, 'cc')},transparent 70%),#0a1020}}")

OUT.append("""
@media (prefers-reduced-motion:reduce){
  .av-ring,.av-ring2,.av::before,.av::after,.nm,.nm::before,.nm::after,.bfx::before,.bfx::after,.cardfx{animation:none!important}
}
""")
css = "\n".join(OUT) + "\n"
target = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "effects.css")
target.write_text(css)
n = sum(1 for i in E.ITEMS if i.split(".")[0] in ("frame", "name", "banner", "card"))
print(f"wrote {target} ({len(css) // 1024} KB) for {n} effects")
